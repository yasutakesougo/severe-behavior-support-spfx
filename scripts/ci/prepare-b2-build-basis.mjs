import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const output = resolve(
  root,
  "spfx/src/adapters/procedure-record-lifecycle-event/b2-build-basis.generated.ts",
);
const sha =
  process.env.B2_HARNESS_BUILD_BASIS_SHA ??
  execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();

if (!/^[0-9a-f]{40}$/.test(sha)) {
  throw new Error("B2_HARNESS_BUILD_BASIS_SHA must be exactly 40 lowercase hex characters");
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `/** Generated by scripts/ci/prepare-b2-build-basis.mjs. Do not edit. */\nexport const B2_HARNESS_BUILD_BASIS_SHA = "${sha}" as const;\n`,
  "utf8",
);
process.stdout.write(`B2 harness build basis: ${sha}\n`);
